import { rm } from "node:fs/promises";
import { join } from "node:path";

const cwd = import.meta.dir;
await rm(join(cwd, "dist"), { recursive: true, force: true });
for (const [mode, resolution, folder] of [["esnext", "bundler", "esm"], ["commonjs", "node", "cjs"]]) {
	const result = Bun.spawnSync(["bunx", "tsc", "-p", "tsconfig.build.json", "--module", mode, "--moduleResolution", resolution, "--outDir", `dist/${folder}`], { cwd, stdout: "inherit", stderr: "inherit" });
	if (result.exitCode) process.exit(result.exitCode);
}
await Bun.write(join(cwd, "dist/cjs/package.json"), JSON.stringify({ type: "commonjs" }));
await Bun.write(join(cwd, "dist/cjs/index.cjs"), '// Generated by SDK build. Do not edit.\nconst api = require("./generated/index.js");\nmodule.exports = Object.assign(api.Inbound, api);\n');
