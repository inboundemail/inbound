import { readdir, rm } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import manifest from "./package.json";

const cwd = import.meta.dir;
await rm(join(cwd, "dist"), { recursive: true, force: true });
for (const [mode, resolution, folder] of [["esnext", "bundler", "esm"], ["commonjs", "node", "cjs"]]) {
	const result = Bun.spawnSync(["bunx", "tsc", "-p", "tsconfig.build.json", "--module", mode, "--moduleResolution", resolution, "--outDir", `dist/${folder}`], { cwd, stdout: "inherit", stderr: "inherit" });
	if (result.exitCode) process.exit(result.exitCode);
	const dir = join(cwd, "dist", folder);
	const entryDir = join(dir, "public");
	const aliases: Record<string, string> = {
		index: "generated/index", client: "generated/index", error: "errors", uploads: "helpers", resource: "resource", "api-promise": "api-promise",
		resources: "generated/index", "core/api-promise": "api-promise", "core/error": "errors",
		"core/resource": "resource", "core/uploads": "helpers", "lib/render": "helpers", "lib/webhooks": "webhooks",
	};
	for (const filename of await readdir(join(dir, "generated"))) {
		if (filename.endsWith(".js")) aliases[`resources/${filename.slice(0, -3)}`] = `generated/${filename.slice(0, -3)}`;
	}
	const header = "// Generated by SDK build. Do not edit.\n";
	for (const [alias, target] of Object.entries(aliases)) {
		const source = JSON.stringify(relative(join(entryDir, dirname(alias)), join(dir, target)).split("\\").join("/") + ".js");
		const esm = `export * from ${source};\n` + (["index", "client"].includes(alias) ? `export { default } from ${source};\n` : "");
		const cjs = alias === "index" ? `const api = require(${source});\nconst Client = new Proxy(api.Inbound, { apply(target, _, args) { return Reflect.construct(target, args); } });\nmodule.exports = Object.assign(Client, api, { Inbound: Client, default: Client });\n` : `module.exports = require(${source});\n`;
		await Bun.write(join(entryDir, `${alias}.js`), header + (folder === "esm" ? esm : cjs));
		await Bun.write(join(entryDir, `${alias}.d.ts`), header + esm);
	}
	const version = JSON.stringify(manifest.version);
	await Bun.write(join(entryDir, "version.js"), header + (folder === "esm" ? "export const VERSION" : "exports.VERSION") + ` = ${version};\n`);
	await Bun.write(join(entryDir, "version.d.ts"), header + `export declare const VERSION = ${version};\n`);
}
await Bun.write(join(cwd, "dist/cjs/package.json"), JSON.stringify({ type: "commonjs" }));
