import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { generate } from "./generate";
import { resources } from "./resources";
import type { Spec } from "./spec";

const root = resolve(import.meta.dir, "../..");
const output = join(root, "packages/inbound-sdk/src/generated");
const spec: Spec = await Bun.file(join(root, "public/openapi.json")).json();
const files = generate(spec, resources);
const check = process.argv.includes("--check");
const dir = check ? await mkdtemp(join(tmpdir(), "inbound-sdk-check-")) : output;
try {
	await mkdir(dir, { recursive: true });
	for (const [name, contents] of Object.entries(files)) await writeFile(join(dir, name), contents);
	const existing: string[] = await readdir(output).catch((error: NodeJS.ErrnoException) => { if (error.code === "ENOENT") return []; throw error; });
	const extra = existing.filter(n => !Object.hasOwn(files, n));
	if (check) {
		const drift = extra.map(n => `obsolete: ${n}`);
		for (const name of Object.keys(files)) {
			if (!existing.includes(name)) drift.push(`missing: ${name}`);
			else if (!(await readFile(join(output, name))).equals(await readFile(join(dir, name)))) drift.push(`changed: ${name}`);
		}
		if (drift.length) throw new Error(`SDK drift:\n  ${drift.join("\n  ")}\nRun: bun run generate:sdk`);
		console.log("sdk:check passed: SDK matches the OpenAPI specification.");
	} else {
		for (const name of extra) {
			if (!(await readFile(join(dir, name), "utf8")).startsWith("// Generated by sdk-codegen")) throw new Error(`Refusing to remove non-generated file: ${name}`);
			await rm(join(dir, name));
		}
		console.log(`Generated ${Object.keys(resources).length} operations in ${Object.keys(files).length} SDK files.`);
	}
} finally {
	if (check) await rm(dir, { recursive: true, force: true });
}
