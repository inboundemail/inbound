import { type Schema, typeOf } from "./schema";
import { type Mapping, operations, type Route, type Spec } from "./spec";

const header = "// Generated by sdk-codegen from OpenAPI. Do not edit.\n\n";
const cap = (s: string) => s[0].toUpperCase() + s.slice(1);
const file = (s: string) => s.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`);
const singular = (s: string) => s === "emailAddresses" ? "EmailAddress" : s === "mailboxes" ? "Mailbox" : cap(s.replace(/(?<!s)s$/, ""));
const prefix = (r: Route) => singular(r.resource) + cap(r.method);
const hasOptions = (r: Route) => r.body || !!r.query.length || !!Object.keys(r.headers).length;
const typeNames = (r: Route) => [prefix(r) + "Response", ...(hasOptions(r) || r.legacyFilename ? [prefix(r) + "Params"] : [])];

// Stainless exposed nested names such as Inbound.DomainListResponse.Data.Stats.
const legacyResources = new Set(["attachments", "domains", "emailAddresses", "emails", "endpoints", "mail"]);
function nestedTypes(parent: string, schema: Schema, depth = 0): string {
	const lines: string[] = [];
	const pad = "\t".repeat(depth + 1);
	for (const [key, prop] of Object.entries(schema.properties ?? {})) {
		const variants = (prop.anyOf ?? prop.oneOf)?.filter(x => x.type !== "null");
		if (variants && variants.length > 1 && key === "config" && parent.startsWith("Endpoint")) {
			variants.forEach(s => {
				if (!s.title || !/^[A-Za-z_$][\w$]*$/.test(s.title)) throw new Error(`Missing config type name in ${parent}`);
				lines.push(`${pad}export type ${s.title} = ${typeOf(s, depth + 1)};`);
			});
		}
		const field = variants?.length === 1 ? variants[0] : prop;
		const obj = field.type === "array" ? field.items : field;
		if (!obj?.properties) continue;
		const word = field.type === "array" ? key.replace(/ies$/, "y").replace(/s$/, "") : key;
		const name = cap(word).replace(/^Dns/, "DNS").replace(/_(\w)/g, (_, c: string) => c.toUpperCase());
		lines.push(`${pad}export type ${name} = NonNullable<${parent}[${JSON.stringify(key)}]>${field.type === "array" ? "[number]" : ""};`);
		const nested = nestedTypes(name, obj, depth + 1);
		if (nested) lines.push(nested);
	}
	return lines.length ? `${"\t".repeat(depth)}export ${depth ? "" : "declare "}namespace ${parent} {\n${lines.join("\n")}\n${"\t".repeat(depth)}}` : "";
}

function types(r: Route) {
	const name = prefix(r);
	const result = r.binary ? "Response" : [...new Set(r.responses.map(s => s ? typeOf(s) : "void"))].join(" | ");
	const lines = [`export type ${name}Response = ${result};`];
	if (hasOptions(r)) lines.push(`export type ${name}Params = ${typeOf(r.options)};`);
	if (r.legacyFilename) lines.push(`export type ${name}Params = { id: string };`);
	if (legacyResources.has(r.resource)) {
		if (r.responses[0]) lines.push(nestedTypes(name + "Response", r.responses[0]));
		if (hasOptions(r)) lines.push(nestedTypes(name + "Params", r.options));
	}
	return lines.filter(Boolean).join("\n\n");
}

function method(r: Route) {
	const args = r.args.map(p => `${p.name}: ${typeOf(p.schema)}`);
	const name = prefix(r);
	const result = `APIPromise<${name}Response>`;
	const options = hasOptions(r);
	if (options) args.push(`params: ${name}Params${r.options.required?.length ? "" : " | null = {}"}`);
	args.push("request?: RequestOptions");
	const path = r.path.replace(/\{([^}]+)\}/g, (_, k) => `\${segment(${k})}`);
	const layout = {
		...(r.body && { body: true }), ...(r.query.length && { query: r.query }),
		...(Object.keys(r.headers).length && { headers: r.headers }), ...(r.binary && { binary: true }),
		...(r.reactEmail && { reactEmail: true }),
		...(r.idempotent && { idempotent: r.idempotent }),
	};
	let signature = `\t${r.method}(${args.join(", ")}): ${result} {`;
	if (r.legacyFilename) signature = `\t${r.method}(${args.join(", ")}): ${result};
	/** @deprecated Prefer retrieve(id, filename). */
	${r.method}(filename: string, params: ${name}Params, request?: RequestOptions): APIPromise<void>;
	${r.method}(first: string, second: string | ${name}Params, request?: RequestOptions): APIPromise<${name}Response | void> {
		const [id, filename] = typeof second === "string" ? [first, second] : [second.id, first];`;
	const lines = [signature, `\t\treturn this._client.resourceRequest(${JSON.stringify(r.verb)}, \`${path}\`, ${options ? "params ?? {}" : "{}"}, ${JSON.stringify(layout)}, request);`, "\t}"];
	if (r.more) {
		const cursors = r.query.filter(k => k === "sinceUid" || k === "sinceModseq");
		const iterArgs = args.map(arg => arg.replace(`params: ${name}Params`, `params: ${name}Params${cursors.length ? ` & { ${cursors.map(k => `${k}?: never`).join("; ")} }` : ""}`));
		lines.push("", `\t${r.method}All(${iterArgs.join(", ")}): AsyncIterableIterator<${name}Response["data"][number]> {`,
			...(cursors.length ? [`\t\tif (${cursors.map(k => `params?.${k} != null || (request?.query && "${k}" in request.query)`).join(" || ")}) throw new TypeError("Use list() for incremental folder sync; listAll() uses offsets");`] : []),
			`\t\treturn paginate(params?.offset, request, (offset, pageRequest) => this.${r.method}(${[...r.args.map(p => p.name), "{ ...params, offset }", "pageRequest"].join(", ")}), ${JSON.stringify(r.more)});`, "\t}");
	}
	return lines.join("\n");
}

export function generate(spec: Spec, mapping: Mapping): Record<string, string> {
	const groups = new Map<string, Route[]>();
	for (const route of operations(spec, mapping)) {
		const routes = groups.get(route.resource) ?? [];
		routes.push(route);
		groups.set(route.resource, routes);
	}
	const files: Record<string, string> = {};
	const names = [...groups.keys()].sort();
	for (const resource of names) {
		const routes = groups.get(resource)!.sort((a, b) => a.method.localeCompare(b.method, "en"));
		const imports = [];
		if (routes.some(r => r.args.length)) imports.push("segment");
		if (routes.some(r => r.more)) imports.push("paginate");
		const blocks = [
			'import { APIResource } from "../resource.js";\nimport type { APIPromise, RequestOptions } from "../runtime.js";' + (imports.length ? `\nimport { ${imports.join(", ")} } from "../runtime.js";` : ""),
			...routes.map(types),
			`export class ${cap(resource)} extends APIResource {
${routes.map(method).join("\n\n")}
}`,
		];
		if (legacyResources.has(resource)) blocks.push(`export declare namespace ${cap(resource)} {
	export type { ${routes.flatMap(typeNames).join(", ")} };
}`);
		files[file(resource) + ".ts"] = header + blocks.join("\n\n") + "\n";
	}
	const module = (n: string) => JSON.stringify(`./${file(n)}.js`);
	const typesFor = (n: string) => groups.get(n)!.flatMap(typeNames);
	const imports = names.map(n => `import { ${cap(n)} as ${cap(n)}Resource,\n${typesFor(n).map(t => `\ttype ${t},`).join("\n")}\n} from ${module(n)};`);
	const properties = names.map(n => `\treadonly ${n} = new ${cap(n)}Resource(this);`);
	if (groups.has("mail")) properties.push("\treadonly threads = this.mail;");
	const aliases = names.map(n => `\texport { ${[`${cap(n)}Resource as ${cap(n)}`, ...typesFor(n).map(t => `type ${t}`)].join(", ")} };`);
	files["index.ts"] = header + `import { type ClientOptions, Transport } from "../runtime.js";
${imports.join("\n")}

export { APIPromise, type ClientOptions, type RequestOptions, type Logger, type LogLevel } from "../runtime.js";
export * from "../errors.js";
export { render, toFile, type ToFileInput, type Uploadable } from "../helpers.js";
export * from "../webhooks.js";
${names.map(n => `export * from ${module(n)};`).join("\n")}

export class Inbound extends Transport {
	static readonly Inbound = Inbound;

${properties.join("\n")}

	constructor(options: ClientOptions = {}) {
		super(options);
	}
}

export declare namespace Inbound {
	export type RequestOptions = import("../runtime.js").RequestOptions;
${aliases.join("\n")}
}

${names.map(n => `Inbound.${cap(n)} = ${cap(n)}Resource;`).join("\n")}

export default Inbound;
`;
	return files;
}
